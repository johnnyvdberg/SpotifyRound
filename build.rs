#[path = "src/etc.rs"]
mod etc;

fn main() {
    println!("cargo:rerun-if-changed=ui");
    slint_build::compile("ui/main.slint").expect("failed to compile the Slint UI");

    // WESL links the shared shader module into each root shader at build time.
    // The output is plain WGSL in OUT_DIR; wgpu never sees the WESL syntax.
    let mut features = wesl::Features::default();
    features.set(
        "full_hd",
        std::env::var_os("CARGO_FEATURE_FULL_HD").is_some(),
    );
    let options = wesl::CompileOptions {
        validate: false,
        features,
        ..Default::default()
    };
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_FULL_HD");
    let compiler = wesl::Compiler::new(options)
        .with_resolver(wesl::resolver::FileResolver::new("src/shaders"));
    let main = wesl::syntax::ModulePath::new(
        wesl::syntax::PathOrigin::Absolute,
        vec!["scene".to_string()],
    );
    let result = compiler
        .compile_module(&main)
        .inspect_err(|e| eprintln!("{e}"))
        .expect("failed to compile scene");
    result.emit_rerun_if_changed();
    result.write_artifact("scene");
    println!("cargo:rerun-if-changed=src/shaders");

    earth_maps();
    museum_paintings();
}

/// The Earth's maps for `globe`, compressed with every mip level: ETC2 RGBA8
/// for the day map with the water mask in its alpha, EAC RG11 for the relief's
/// two slopes, EAC R11 for the city lights and the clouds. Written to OUT_DIR
/// with `earth.rs`, which `globe` includes. Encoding takes a while, so it is
/// skipped while a stamp of the inputs says the output is current.
fn earth_maps() {
    use etc::Layout;
    use std::hash::{Hash, Hasher};

    const SOURCES: [&str; 5] = [
        "day.jpg",
        "night.jpg",
        "clouds.jpg",
        "normal.tif",
        "specular.tif",
    ];
    println!("cargo:rerun-if-changed=src/etc.rs");
    let out = std::path::PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    let read = |name: &str| {
        let path = format!("assets/earth/{name}");
        println!("cargo:rerun-if-changed={path}");
        std::fs::read(&path).unwrap_or_else(|e| panic!("reading {path}: {e}"))
    };
    let bytes = SOURCES.map(read);
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    bytes.hash(&mut hasher);
    std::fs::read("src/etc.rs")
        .expect("src/etc.rs")
        .hash(&mut hasher);
    let stamp = format!("{:016x}", hasher.finish());
    let stamp_path = out.join("earth.stamp");
    if std::fs::read_to_string(&stamp_path).is_ok_and(|s| s == stamp) {
        return;
    }

    let decode = |data: &[u8]| image::load_from_memory(data).expect("an Earth map");
    let [day, night, clouds, normal, specular] = bytes.each_ref().map(|b| decode(b));
    let (width, height) = (day.width(), day.height());
    // The water mask is half the day map's size; brought up to it, it rides in
    // the day map's alpha, so one fetch answers colour and sea together.
    let water = image::imageops::resize(
        &specular.to_luma8(),
        width,
        height,
        image::imageops::FilterType::Triangle,
    );
    let day: Vec<u8> = day
        .to_rgb8()
        .pixels()
        .zip(water.pixels())
        .flat_map(|(c, w)| [c[0], c[1], c[2], w[0]])
        .collect();
    let relief: Vec<u8> = normal
        .to_rgb8()
        .pixels()
        .flat_map(|c| [c[0], c[1]])
        .collect();

    let maps = [
        ("day", Layout::Rgba, width, height, day, 3),
        (
            "night",
            Layout::R11,
            night.width(),
            night.height(),
            night.to_luma8().into_raw(),
            0,
        ),
        (
            "clouds",
            Layout::R11,
            clouds.width(),
            clouds.height(),
            clouds.to_luma8().into_raw(),
            0,
        ),
        (
            "relief",
            Layout::Rg11,
            normal.width(),
            normal.height(),
            relief,
            0,
        ),
    ];
    let mut index = String::from("// Generated by build.rs from assets/earth.\n");
    for (name, layout, width, height, texels, srgb) in maps {
        let mut packed = Vec::new();
        let mut levels = 0;
        for (w, h, level) in mip_chain(
            texels,
            width as usize,
            height as usize,
            layout.channels(),
            srgb,
        ) {
            packed.extend(layout.compress(&level, w, h));
            levels += 1;
        }
        let file = format!("earth-{name}.etc");
        std::fs::write(out.join(&file), packed).expect("writing a compressed map");
        index += &format!(
            "pub const {}: Packed = Packed {{ width: {width}, height: {height}, levels: {levels}, \
             layout: Layout::{layout:?}, data: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{file}\")) }};\n",
            name.to_uppercase(),
        );
    }
    std::fs::write(out.join("earth.rs"), index).expect("writing earth.rs");
    std::fs::write(stamp_path, stamp).expect("writing the stamp");
}

/// Every mip level of an image, `channels` bytes a texel, down to 1 × 1: each
/// level the 2 × 2 mean of the one before (the last row or column repeated
/// where a side is odd). The first `srgb` channels are averaged in linear
/// light, as the GPU's own mip chain of an sRGB texture was.
fn mip_chain(
    texels: Vec<u8>,
    width: usize,
    height: usize,
    channels: usize,
    srgb: usize,
) -> Vec<(usize, usize, Vec<u8>)> {
    let to_linear: Vec<f32> = (0..256)
        .map(|v| {
            let c = v as f32 / 255.0;
            if c <= 0.04045 {
                c / 12.92
            } else {
                ((c + 0.055) / 1.055).powf(2.4)
            }
        })
        .collect();
    let to_srgb = |l: f32| {
        let c = if l <= 0.0031308 {
            l * 12.92
        } else {
            1.055 * l.powf(1.0 / 2.4) - 0.055
        };
        (c * 255.0).round().clamp(0.0, 255.0) as u8
    };
    let mut levels = vec![(width, height, texels)];
    loop {
        let (w, h, last) = levels.last().expect("a level");
        let (w, h) = (*w, *h);
        if w == 1 && h == 1 {
            break;
        }
        let (nw, nh) = ((w / 2).max(1), (h / 2).max(1));
        let mut next = vec![0u8; nw * nh * channels];
        for y in 0..nh {
            for x in 0..nw {
                for c in 0..channels {
                    let mut sum = 0.0;
                    for (dx, dy) in [(0, 0), (1, 0), (0, 1), (1, 1)] {
                        let (sx, sy) = ((x * 2 + dx).min(w - 1), (y * 2 + dy).min(h - 1));
                        let v = last[(sy * w + sx) * channels + c];
                        sum += if c < srgb {
                            to_linear[v as usize]
                        } else {
                            v as f32
                        };
                    }
                    let mean = sum / 4.0;
                    next[(y * nw + x) * channels + c] = if c < srgb {
                        to_srgb(mean)
                    } else {
                        mean.round() as u8
                    };
                }
            }
        }
        levels.push((nw, nh, next));
    }
    levels
}

/// The underwater museum's paintings (`assets/museum/paintings.tsv`), each
/// stretched square to one layer of [`PAINTING`] texels with its mip levels
/// down to a block, ETC2 RGB8, one after another in `museum-paintings.etc`;
/// and `museum.rs`, which `dive3d::museum` includes: each painting's size,
/// hall, title and painter, in the layers' order. The quad a painting hangs
/// on has the painting's own shape, so the stretch comes out again.
fn museum_paintings() {
    use std::hash::{Hash, Hasher};

    const PAINTING: usize = 512;
    const LIST: &str = "assets/museum/paintings.tsv";
    println!("cargo:rerun-if-changed={LIST}");
    let out = std::path::PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    let list = std::fs::read_to_string(LIST).expect(LIST);
    let rows: Vec<Vec<&str>> = list
        .lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
        .map(|l| l.split('\t').collect())
        .collect();
    let images: Vec<Vec<u8>> = rows
        .iter()
        .map(|r| {
            let path = format!("assets/museum/{}", r[0]);
            println!("cargo:rerun-if-changed={path}");
            std::fs::read(&path).unwrap_or_else(|e| panic!("reading {path}: {e}"))
        })
        .collect();
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    (&list, &images, PAINTING).hash(&mut hasher);
    std::fs::read("src/etc.rs")
        .expect("src/etc.rs")
        .hash(&mut hasher);
    let stamp = format!("{:016x}", hasher.finish());
    let stamp_path = out.join("museum.stamp");
    if std::fs::read_to_string(&stamp_path).is_ok_and(|s| s == stamp) {
        return;
    }

    let mut packed = Vec::new();
    let mut levels = 0;
    let mut pixels = Vec::new();
    for bytes in &images {
        let image = image::load_from_memory(bytes)
            .expect("a painting")
            .to_rgba8();
        pixels.push(image.dimensions());
        let square = image::imageops::resize(
            &image,
            PAINTING as u32,
            PAINTING as u32,
            image::imageops::FilterType::Triangle,
        );
        // Down to one block: a smaller level would be a block all the same.
        let chain: Vec<_> = mip_chain(square.into_raw(), PAINTING, PAINTING, 4, 3)
            .into_iter()
            .take_while(|&(w, _, _)| w >= 4)
            .collect();
        levels = chain.len();
        for (w, h, level) in chain {
            packed.extend(etc::Layout::Rgb.compress(&level, w, h));
        }
    }
    std::fs::write(out.join("museum-paintings.etc"), &packed).expect("writing the paintings");
    let mut index = String::from(
        "// Generated by build.rs from assets/museum/paintings.tsv.\n\
         pub const SIZE: u32 = ",
    );
    index += &format!(
        "{PAINTING};\npub const LEVELS: u32 = {levels};\n\
         pub const DATA: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/museum-paintings.etc\"));\n\
         pub const PAINTINGS: [Painting; {}] = [\n",
        rows.len()
    );
    for (r, (w, h)) in rows.iter().zip(&pixels) {
        index += &format!(
            "    Painting {{ masters: {}, height: {:?}, width: {:?}, pixels: [{w}, {h}], title: {:?}, painter: {:?} }},\n",
            r[1] == "masters",
            r[2].parse::<f32>().expect("a height"),
            r[3].parse::<f32>().expect("a width"),
            r[6],
            r[7],
        );
    }
    index += "];\n";
    std::fs::write(out.join("museum.rs"), index).expect("writing museum.rs");
    std::fs::write(stamp_path, stamp).expect("writing the stamp");
}
